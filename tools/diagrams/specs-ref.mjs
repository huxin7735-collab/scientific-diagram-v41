import fs from 'node:fs';
import path from 'node:path';

const REF = path.resolve(process.cwd(), '参照物');

/** refer 候选目录：排除 `_备份*` 遗留备份目录。 */
const refDirNames = () => fs.readdirSync(REF, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith('_备份'))
  .map((d) => d.name);

const FIG_DIRS = refDirNames();

/** 题号 + 图号 → 参照物 下的真实目录名（恰好 1 命中，否则 throw）。
    导出仅供自检脚本调用；build.mjs 只消费 figures。 */
export const dirFor = (paper, no) => {
  const key = `${paper}题_${no}`;
  const cands = FIG_DIRS.filter((n) =>
    n === key || (n.startsWith(key) && !/[0-9.]/.test(n.charAt(key.length))));
  if (cands.length !== 1) {
    throw new Error(
      `参照物 目录解析失败：键「${key}」命中 ${cands.length} 个目录，要求恰好 1 个（禁止静默取第一个）。\n`
      + `  候选：${cands.length ? cands.join(' / ') : '（无）'}\n`
      + `  参照物 顶层目录（已排除 _备份*）：${FIG_DIRS.join(' / ')}`,
    );
  }
  return cands[0];
};

const OUTDIR = (paper, no) => path.join(REF, dirFor(paper, no));
const SRC = (paper, no) => `参照物/${dirFor(paper, no)}/00-图题与描述.md`;

